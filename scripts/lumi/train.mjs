#!/usr/bin/env node
// Trains the Lumi action ranker on self-play and writes packages/cli/src/ranker-weights.ts. One command:
//   pnpm --filter @shipvo/cli build && node scripts/lumi/train.mjs [--out file.ts] [--seeds 40]
// Self-play: the walker (model off) explores the training apps at several step budgets and seeds. Every action is a row.
// Label: 1 when the action reached a new screen or produced a finding. The held-out `account` app is never used.
// The same command on the same code gives the same file.
import { writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { SPEC_APPS, specDriver } from "./spec-app.mjs";
import { TRAIN_APPS } from "./train-apps.mjs";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "../..");
const arg = (k, d) => { const i = process.argv.indexOf(`--${k}`); return i > 0 ? process.argv[i + 1] : d; };
const out = resolve(arg("out", resolve(root, "packages/cli/src/ranker-weights.ts")));
const seeds = Number(arg("seeds", 40));
const { walk } = await import(resolve(root, "packages/cli/dist/explore.js"));
const { FEATURES, featureVector, train } = await import(resolve(root, "packages/cli/dist/ranker.js"));

// Training apps: the tuning spec apps (not held out) and the training-only apps.
const apps = [...SPEC_APPS.filter((a) => !a.heldOut), ...TRAIN_APPS];
const rows = [];
const toRow = (r) => ({
  x: featureVector({
    kind: r.action.kind, role: r.action.role, risky: r.action.risky, invalid_input: r.action.invalid_input, enter: r.action.enter, nth: r.action.nth,
    depth: r.screen.depth, tried: r.screen.tried, actions: r.screen.actions,
    fields: Object.values(r.screen.field_types).reduce((a, b) => a + b, 0),
  }),
  y: r.outcome.new_screen || r.outcome.finding ? 1 : 0,
});
for (const app of apps) {
  for (let seed = 1; seed <= seeds; seed++) {
    for (const maxSteps of [8, 20, 60]) {
      await walk(specDriver(app, new Set()), {
        app: app.id, seed, maxSteps, maxDepth: 4, settleMs: 0,
        onAction: (r) => rows.push(toRow(r)),
      });
    }
  }
}
const m = train(rows);
const r6 = (n) => Math.round(n * 1e6) / 1e6;
const model = { version: 1, features: [...FEATURES], bias: r6(m.bias), weights: m.weights.map(r6), trainedOn: `${apps.map((a) => a.id).join(", ")}; ${seeds} seeds; ${rows.length} actions; ${rows.filter((r) => r.y).length} positive` };
writeFileSync(out, `// Generated by scripts/lumi/train.mjs. Do not edit by hand.\nimport type { RankerModel } from "./ranker.js";\n\nexport const RANKER_MODEL: RankerModel = ${JSON.stringify(model, null, 2)};\n`);
console.log(`wrote ${out}: ${model.trainedOn}`);
